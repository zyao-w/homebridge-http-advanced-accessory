#!/usr/bin/env node
// Regenerates src/hap-names.js, the HomeKit names that the form offers, from HAP-NodeJS: the characteristics, and the
// services with the characteristics each of them has.
//
//   node scripts/build-hap-names.js <folder> [<folder> ...]
//
// Each folder has hap-nodejs (Homebridge 1.x) or @homebridge/hap-nodejs (Homebridge 2.x) in its node_modules, for
// example an `npm install` of it, or a Homebridge install. Give one folder per Homebridge line that the plugin
// supports: the lists are combined, so that the form offers what at least one of them has. A service must be in every
// one of them, because an unknown service keeps the device from loading, while an unknown characteristic only logs a
// warning.
//
// The lists are a convenience for the form; the plugin itself accepts any name that the service has, so a name that is
// missing here still works when it is typed in the JSON config.
const fs = require("fs");
const path = require("path");

const folders = process.argv.slice(2).map((folder) => path.resolve(folder));
if (folders.length === 0) {
	console.error("Usage: node scripts/build-hap-names.js <folder> [<folder> ...]");
	process.exit(1);
}

// HomeKit writes a few names with a hyphen ("Current Heater-Cooler State"). Whitespace and hyphens are left out, as
// the plugin does when it matches a name (see matchKey in src/device.js); the dot of "PM2.5 Density" is kept.
const nameOf = (characteristic) => characteristic.displayName.replace(/[\s-]/g, "");
const byName = (a, b) => a.localeCompare(b, "en");

function load(folder) {
	for (const name of ["@homebridge/hap-nodejs", "hap-nodejs"]) {
		let entry;
		try {
			entry = require.resolve(name, { paths: [folder] });
		} catch {
			continue;
		}
		const manifest = require(require.resolve(`${name}/package.json`, { paths: [path.dirname(entry)] }));
		return { name: `${name}@${manifest.version}`, hap: require(entry) };
	}
	console.error(`Cannot find hap-nodejs or @homebridge/hap-nodejs in ${folder}`);
	process.exit(1);
}

/** The characteristic names, and for each service (by the name of its class) what it has. */
function read({ hap }) {
	const characteristics = new Set();
	for (const Characteristic of Object.values(hap.Characteristic)) {
		if (typeof Characteristic !== "function" || !Characteristic.UUID) continue;
		try {
			characteristics.add(nameOf(new Characteristic()));
		} catch {
			// A characteristic that cannot be created without arguments is left out
		}
	}

	// Some services have a second, deprecated name for the same class (BatteryService for Battery). The name of the
	// class is the one that is offered, because it exists in every version; the plugin still accepts the others.
	const classes = new Map();
	for (const [key, Service] of Object.entries(hap.Service)) {
		if (typeof Service !== "function" || !Service.UUID) continue;
		const known = classes.get(Service.UUID);
		if (!known || (Service.name === key && known.key !== Service.name)) classes.set(Service.UUID, { key, Service });
	}

	const services = new Map();
	for (const { key, Service } of classes.values()) {
		// The plugin adds the Accessory Information service itself, so it cannot be chosen as the service of a device
		if (key === "AccessoryInformation") continue;
		try {
			const service = new Service("name");
			services.set(key, {
				required: new Set(service.characteristics.map(nameOf)),
				optional: new Set(service.optionalCharacteristics.map(nameOf)),
			});
		} catch {
			// A service that cannot be created is left out
		}
	}
	return { characteristics, services };
}

const sources = folders.map(load);
const reads = sources.map(read);

const characteristics = new Set(reads.flatMap((one) => [...one.characteristics]));
const serviceNames = [...reads[0].services.keys()].filter((name) => reads.every((one) => one.services.has(name)));

const services = {};
for (const name of serviceNames.sort(byName)) {
	const merge = (field) => [...new Set(reads.flatMap((one) => [...one.services.get(name)[field]]))].sort(byName);
	services[name] = { required: merge("required"), optional: merge("optional") };
	// What a version has among the optional ones may be required in another; it is listed once, as required
	services[name].optional = services[name].optional.filter((one) => !services[name].required.includes(one));
}
for (const { services: one } of reads) {
	const dropped = [...one.keys()].filter((name) => !serviceNames.includes(name));
	if (dropped.length) console.log(`Left out, not in every version: ${dropped.join(", ")}`);
}

const indent = (value) => JSON.stringify(value, null, "\t").replace(/\n/g, "\n\t");
const text = `// Generated by scripts/build-hap-names.js from ${sources.map((source) => source.name).join(" and ")}. Do not edit by hand.
// The characteristic and service names that the form of the plugin offers.
module.exports = {
	HAP_VERSIONS: ${JSON.stringify(sources.map((source) => source.name))},
	CHARACTERISTICS: ${indent([...characteristics].filter(Boolean).sort(byName))},
	// For each service: the characteristics it always has, and those that can be added to it
	SERVICES: ${indent(services)},
};
`;
fs.writeFileSync(path.join(__dirname, "..", "src", "hap-names.js"), text);
console.log(
	`Wrote ${characteristics.size} characteristics and ${Object.keys(services).length} services from ${sources.map((source) => source.name).join(" and ")}`
);
